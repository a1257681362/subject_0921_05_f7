-- ---------------------------------------------------------------------------
-- 对外开放接口 nonce 防重放（HMAC 签名鉴权，见 OpenApiSignInterceptor）
-- 仅已通过验签的请求才会写入本表；(app_id, nonce) 唯一约束是重复 nonce 的权威判定，
-- 重复直接拒绝（NONCE_DUPLICATED）。保留窗口 30 分钟 > 签名时间窗 15 分钟，
-- 因此定时清理（每分钟）永远不会在时间窗内提前删掉尚未过期的 nonce。
-- 本表是全库"禁止物理删除"约定的例外（与 t_batch_job 同类）：属运维临时数据，
-- expire_time 到期由 OpenApiNonceMaintenance 定时物理清理。
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_openapi_nonce (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id       VARCHAR(64)  NOT NULL,
    nonce        VARCHAR(64)  NOT NULL,
    expire_time  TIMESTAMP    NOT NULL,                    -- 过期时间 = 入库时间 + 30 分钟，到期物理清理
    created_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_openapi_nonce UNIQUE (app_id, nonce)
);

CREATE INDEX IF NOT EXISTS idx_openapi_nonce_expire ON t_openapi_nonce (expire_time);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('openapi-sign-1', '对外开放加工单查询 HMAC 签名鉴权与 nonce 防重放（15分钟时间窗/30分钟去重/到期清理）');
